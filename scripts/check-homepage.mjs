import fs from 'node:fs';
import cp from 'node:child_process';
import assert from 'node:assert/strict';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const before=cp.execFileSync('git',['show','HEAD:index.html'],{cwd:root,encoding:'utf8'});
const home=fs.readFileSync(path.join(root,'index.html'),'utf8');
const links=s=>new Set([...s.matchAll(/href="([^"]+)"/g)].map(m=>m[1]));
const oldLinks=links(before),newLinks=links(home);
for(const url of oldLinks)if(url.startsWith('/CI-blog/')||url.startsWith('/industries/'))assert.ok(newLinks.has(url),'Missing original destination: '+url);
const ids=new Set([...home.matchAll(/id="([^"]+)"/g)].map(m=>m[1]));
for(const url of newLinks)if(url.startsWith('#'))assert.ok(ids.has(url.slice(1)),'Missing anchor: '+url);
for(const [,url] of home.matchAll(/(?:src|href)="(\/assets\/[^"?]+)(?:\?[^\"]*)?"/g))assert.ok(fs.existsSync(path.join(root,url)),'Missing asset: '+url);
assert.ok(!home.includes('—'),'Em dash in homepage');
assert.ok(home.indexOf('id="services"')<home.indexOf('class="feature-grid"'),'Services should precede article feeds');
const samples=JSON.parse(fs.readFileSync(path.join(root,'assets/deliverables.json'),'utf8'));
assert.equal(samples.en.length,3);assert.equal(samples.zh.length,3);
const contact=fs.readFileSync(path.join(root,'contact/index.html'),'utf8');
for(const field of ['name','email','message'])assert.ok(contact.includes('name="'+field+'"'));
assert.ok(contact.indexOf('</form>')<contact.indexOf('id="successMsg"'));
console.log('PASS: original article and industry links, anchors, assets, bilingual samples and contact field preservation');
